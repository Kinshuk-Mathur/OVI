import "fake-indexeddb/auto";
import test from "node:test";
import assert from "node:assert/strict";
import { createUserWithEmailAndPassword } from "firebase/auth";
import { doc, getDocFromServer } from "firebase/firestore";
import { getBytes, ref } from "firebase/storage";

Object.defineProperty(globalThis, "window", { value: new EventTarget(), configurable: true });
Object.defineProperty(globalThis, "navigator", { value: { onLine: true }, configurable: true });
process.env.NEXT_PUBLIC_FIREBASE_API_KEY = "demo-key";
process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN = "demo-ovi.firebaseapp.com";
process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID = "demo-ovi";
process.env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET = "demo-ovi.appspot.com";
process.env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID = "123";
process.env.NEXT_PUBLIC_FIREBASE_APP_ID = "1:123:web:demo";
process.env.NEXT_PUBLIC_FIREBASE_USE_EMULATORS = "true";

test("encrypted journal, media, and conflict branches survive Firebase transactions", async () => {
  const { getFirebaseServices } = await import("../lib/firebase/client");
  const { createVaultOnce, loadVault, updateVaultAfterRecovery } = await import("../lib/firebase/repository");
  const { createVault, recoverVault, unlockVault, decryptRecord, decodeText } = await import("../lib/security/vault");
  const { JournalWorkspace } = await import("../lib/journal/workspace");
  const { listCheckpoints } = await import("../lib/journal/checkpoints");
  const { saveEncryptedPhoto, getEncryptedPhoto, uploadPendingPhotos } = await import("../lib/journal/media");
  const services = getFirebaseServices();
  const credential = await createUserWithEmailAndPassword(services.auth, `${crypto.randomUUID()}@example.test`, "password-for-emulator");
  const uid = credential.user.uid;
  const vault = await createVault(uid, "an adequately long test password");
  await createVaultOnce(uid, vault.metadata, "Test");
  assert.equal((await loadVault(uid))?.revision, 1);
  await assert.rejects(createVaultOnce(uid, vault.metadata));
  const { createConversation, addConversationMessage } = await import("../lib/firebase/chat");
  const conversationId = await createConversation(uid, vault.masterKey, { title: "Private conversation" });
  const messageId = await addConversationMessage(uid, vault.masterKey, conversationId, { role: "user", text: "Private message" });
  const message = await getDocFromServer(doc(services.db, "users", uid, "conversations", conversationId, "messages", messageId));
  assert.equal(JSON.stringify(message.data()).includes("Private message"), false);
  const messageBytes = await decryptRecord(vault.masterKey, uid, JSON.stringify(["message", conversationId, messageId]), message.data()!.encrypted);
  assert.equal(JSON.parse(decodeText(messageBytes)).text, "Private message");
  const first = new JournalWorkspace(uid, vault.masterKey), second = new JournalWorkspace(uid, vault.masterKey);
  first.start();
  try {
    const initial = await first.open("journal-1", true);
    const draft = { id: "journal-1", title: "Private title", entryDate: "2026-11-23", createdAt: Date.now(), updatedAt: Date.now(), content: { type: "doc", content: [{ type: "paragraph", content: [{ type: "text", text: "first private sentence" }] }] } };
    await initial.handle.save(draft);
    const local = await listCheckpoints(uid);
    assert.equal(JSON.stringify(local).includes("first private sentence"), false);
    const restored = await first.open("journal-1", true);
    assert.equal(restored.draft?.title, "Private title");
    Object.defineProperty(navigator, "onLine", { value: false, configurable: true });
    const reloaded = new JournalWorkspace(uid, vault.masterKey);
    reloaded.start();
    try { assert.equal((await reloaded.open("journal-1", true)).draft?.title, "Private title"); }
    finally { reloaded.close(); }
    await first.syncPending();
    const refDoc = doc(services.db, "users", uid, "journals", "journal-1");
    assert.equal((await getDocFromServer(refDoc)).exists(), false);
    Object.defineProperty(navigator, "onLine", { value: true, configurable: true });
    await first.syncPending();
    const cloud = await getDocFromServer(refDoc);
    assert.equal(cloud.data()?.revision, 1);
    assert.equal(JSON.stringify(cloud.data()).includes("Private title"), false);
    second.start();
    const other = await second.open("journal-1", false);
    assert.equal(other.draft?.title, "Private title");
    await initial.handle.save({ ...draft, title: "First device" });
    await first.syncPending();
    await other.handle.save({ ...draft, title: "Second device" });
    await second.syncPending();
    const latest = await getDocFromServer(refDoc);
    assert.equal(latest.data()?.revision, 2);
    const clear = await decryptRecord(vault.masterKey, uid, JSON.stringify(["journal", "journal-1"]), latest.data()!.encrypted);
    assert.equal(JSON.parse(decodeText(clear)).title, "First device");
    const pending = await listCheckpoints(uid);
    assert.ok(pending.some((branch) => branch.branchId === other.handle.branchId && branch.localRevision > branch.syncedLocalRevision));
    const copyId = await second.forkLocalCopy(`journal-1~${other.handle.branchId}`);
    const copy = await second.open(copyId, false);
    assert.equal(copy.draft?.title, "Second device");
    assert.notEqual(copy.handle.journalId, "journal-1");
    const photo = new Blob([new Uint8Array([1, 2, 3, 4, 5])], { type: "image/jpeg" });
    await saveEncryptedPhoto(uid, vault.masterKey, "journal-1", "media-1", photo);
    await uploadPendingPhotos(uid, "journal-1");
    const remoteBytes = new Uint8Array(await getBytes(ref(services.storage, `users/${uid}/journal-media/journal-1/media-1`)));
    const mediaRecord = JSON.parse(new TextDecoder().decode(remoteBytes));
    const mediaPlain = await decryptRecord(vault.masterKey, uid, JSON.stringify(["media", "journal-1", "media-1"]), mediaRecord);
    assert.deepEqual(Array.from(mediaPlain.slice(-5)), [1, 2, 3, 4, 5]);
    assert.deepEqual(Array.from(new Uint8Array(await (await getEncryptedPhoto(uid, vault.masterKey, "journal-1", "media-1"))!.arrayBuffer())), [1, 2, 3, 4, 5]);
    const legacy = await import("../lib/journal-storage");
    const { migrateLegacyJournals } = await import("../lib/journal/migrate");
    await legacy.saveJournalPhoto("old-photo", photo);
    await legacy.saveJournalDraft({ ...draft, id: "old-draft", title: "Earlier local entry", content: { type: "doc", content: [{ type: "journalImage", attrs: { imageId: "old-photo", note: "a note", width: 280, offset: 10 } }] } });
    const imported = await migrateLegacyJournals(first);
    assert.equal(imported.imported, 1);
    assert.equal(imported.pending, 0);
    assert.equal((await legacy.getJournalDraft("old-draft"))?.title, "Earlier local entry");
    assert.ok(await legacy.getJournalPhoto("old-photo"));
    assert.equal((await migrateLegacyJournals(first)).skipped, 1);
    const missing = await first.open("missing-photo-journal", true);
    await missing.handle.save({ ...draft, id: "missing-photo-journal", content: { type: "doc", content: [{ type: "journalImage", attrs: { journalId: "missing-photo-journal", imageId: "missing" } }] } });
    await first.syncPending();
    assert.equal((await getDocFromServer(doc(services.db, "users", uid, "journals", "missing-photo-journal"))).exists(), false);
    assert.ok((await listCheckpoints(uid)).some((branch) => branch.journalId === "missing-photo-journal" && branch.localRevision > branch.syncedLocalRevision));
    const recovered = await recoverVault(uid, vault.recoveryKey, "a different secure password", vault.metadata);
    await updateVaultAfterRecovery(uid, recovered.metadata, 1);
    const refreshedVault = await loadVault(uid);
    assert.equal(refreshedVault?.revision, 2);
    const unlocked = await unlockVault(uid, "a different secure password", refreshedVault!);
    const recoveredBytes = await decryptRecord(unlocked, uid, JSON.stringify(["journal", "journal-1"]), latest.data()!.encrypted);
    assert.equal(JSON.parse(decodeText(recoveredBytes)).title, "First device");
    await assert.rejects(updateVaultAfterRecovery(uid, recovered.metadata, 1));
  } finally { first.close(); second.close(); await services.auth.signOut(); }
});
